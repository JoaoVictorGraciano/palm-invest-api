-- Baseline: schema como existia antes do Flyway (gerado pelo ddl-auto=update + ALTERs manuais).
-- Em bancos que ja tem as tabelas, o Flyway marca esta versao como aplicada sem executa-la
-- (spring.flyway.baseline-on-migrate=true). Em bancos vazios (e no H2 dos testes), ela roda.
-- SQL mantido no subconjunto comum a PostgreSQL e H2 (MODE=PostgreSQL).

CREATE TABLE usuarios (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(255),
    email VARCHAR(255),
    senha VARCHAR(255),
    CONSTRAINT uk_usuarios_email UNIQUE (email)
);

CREATE TABLE transactions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type             VARCHAR(255),
    asset_symbol     VARCHAR(255),
    quantity         NUMERIC(19, 8),
    price            NUMERIC(19, 8),
    transaction_date TIMESTAMP(6),
    broker           VARCHAR(255),
    fee              NUMERIC(38, 2),
    observation      VARCHAR(255),
    usuario_id       BIGINT NOT NULL,
    CONSTRAINT fk_transactions_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);
