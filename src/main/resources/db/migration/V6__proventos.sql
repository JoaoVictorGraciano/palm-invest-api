-- Proventos recebidos (dividendos, JCP, rendimentos de FII, amortizações). Tabela nova: nenhum dado existente muda.
-- O valor líquido (valor_bruto - ir_retido) é calculado pela API e não é gravado.
-- As regras de valor também ficam no banco, como defesa caso a validação da API seja contornada.
CREATE TABLE proventos (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     BIGINT         NOT NULL,
    asset_symbol   VARCHAR(20)    NOT NULL,
    asset_class    VARCHAR(20)    NOT NULL,
    tipo           VARCHAR(20)    NOT NULL,
    data_pagamento DATE           NOT NULL,
    valor_bruto    NUMERIC(19, 2) NOT NULL,
    ir_retido      NUMERIC(19, 2) DEFAULT 0 NOT NULL,
    observacao     VARCHAR(255),
    CONSTRAINT fk_proventos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT ck_proventos_tipo CHECK (tipo IN ('DIVIDENDO', 'JCP', 'RENDIMENTO', 'AMORTIZACAO')),
    CONSTRAINT ck_proventos_asset_class CHECK (asset_class IN ('STOCK', 'CRYPTO', 'FII', 'ETF', 'BDR')),
    CONSTRAINT ck_proventos_valor_bruto CHECK (valor_bruto > 0),
    CONSTRAINT ck_proventos_ir_retido CHECK (ir_retido >= 0 AND ir_retido <= valor_bruto)
);

-- Listagem e resumo filtram por usuário e período de pagamento
CREATE INDEX ix_proventos_usuario_data ON proventos (usuario_id, data_pagamento);
